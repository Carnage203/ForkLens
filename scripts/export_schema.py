"""Write the PostgreSQL DDL for every table to db/schema.sql (paste it into Supabase's SQL Editor).

Usage:  python -m scripts.export_schema
Useful when your network blocks direct Postgres connections, so scripts.init_db cannot reach the database.
"""
from __future__ import annotations

from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from backend.db.models import Base

OUT = Path(__file__).resolve().parent.parent / "db" / "schema.sql"


def main() -> None:
    """Render CREATE TABLE / CREATE INDEX statements with IF NOT EXISTS so the script is safe to re-run."""
    dialect = postgresql.dialect()
    statements = ["-- ForkLens schema (generated by scripts/export_schema.py). Safe to run more than once."]
    for table in Base.metadata.sorted_tables:
        statements.append(str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
        statements += [str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect)).strip() + ";"
                       for index in sorted(table.indexes, key=lambda i: i.name or "")]
        # Supabase exposes public tables through its REST API + public anon key: RLS with no policies blocks that.
        # The backend connects as the postgres role, which bypasses RLS.
        statements.append(f"ALTER TABLE {table.name} ENABLE ROW LEVEL SECURITY;")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n\n".join(statements) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(Base.metadata.sorted_tables)} tables)")


if __name__ == "__main__":
    main()
